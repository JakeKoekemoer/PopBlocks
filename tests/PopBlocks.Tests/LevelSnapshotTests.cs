using PopBlocks.Engine;
using PopBlocks.Engine.Levels;
using PopBlocks.Engine.Models;
using Xunit;

namespace PopBlocks.Tests;

/// <summary>
/// A regression snapshot of every generated level: its goals, move limit, speed, view rules and starting pile.
/// Levels are meant to be identical on every device and after every update, so any change shows up here and has to be
/// approved on purpose. To approve a deliberate change, run the tests once with POPBLOCKS_WRITE_SNAPSHOT set to the
/// path of LevelSnapshotData.cs, review the diff, and commit it.
/// </summary>
public class LevelSnapshotTests
{
    public const int LastSnapshotLevel = 220;

    /// <summary>
    /// The one hand-made Story level, which must never change whatever else is retuned: the first "new shapes" level.
    /// (The ten tutorial lessons are frozen separately, by <see cref="LessonSnapshotData"/>.)
    /// </summary>
    public const int FrozenLevel = 11;

    public static string Describe(int n) => Describe(n, LevelCatalog.Get(n));

    /// <summary>Lesson <paramref name="n"/> of the tutorial, described in the same format.</summary>
    public static string DescribeLesson(int n) => Describe(n, LevelCatalog.Lesson(n));

    private static string Describe(int n, LevelDefinition level)
    {
        var goals = string.Join(";", level.Goals.Select(g => $"{g.Kind}:{g.Target}:{(int)g.Colour}{(g.MinWaves > 0 ? ":w" + g.MinWaves : "")}"));
        return $"{n}|{level.Tier}|{goals}|m{level.MoveLimit}|f{level.FallIntervalMs}|c{level.Colours}" +
               $"|{(level.FlipView ? "flip" : "-")}|p{level.NoPopPenalty}|{PileHash(level):x8}" +
               (level.Bonus is { } b ? $"|bonus {b.Kind}:{b.Target}:{(int)b.Colour}:{b.MemoryId}" : "");
    }

    /// <summary>FNV-1a over the starting board, so the hash is the same on every platform.</summary>
    public static uint PileHash(LevelDefinition level)
    {
        var board = level.CreateBoard();
        uint hash = 2166136261;
        for (int y = 0; y < board.Height; y++)
            for (int x = 0; x < board.Width; x++)
                hash = unchecked((hash ^ (uint)(int)board[x, y]) * 16777619);
        return hash;
    }

    public static string Build()
    {
        var lines = Enumerable.Range(1, LastSnapshotLevel).Select(Describe);
        return string.Join("\n", lines);
    }

    [Fact]
    public void Write_the_snapshot_when_asked()
    {
        string? path = Environment.GetEnvironmentVariable("POPBLOCKS_WRITE_SNAPSHOT");
        if (string.IsNullOrEmpty(path)) return;

        var text = "namespace PopBlocks.Tests;\n\n/// <summary>Generated by LevelSnapshotTests. See that class before editing.</summary>\n" +
                   "public static class LevelSnapshotData\n{\n    public const string Lines = \"\"\"\n" +
                   Build() + "\n\"\"\";\n}\n";
        File.WriteAllText(path, text);
    }

    [Fact]
    public void Levels_match_the_approved_snapshot()
    {
        if (Environment.GetEnvironmentVariable("POPBLOCKS_WRITE_SNAPSHOT") is { Length: > 0 }) return;

        var expected = LevelSnapshotData.Lines.Split('\n', StringSplitOptions.RemoveEmptyEntries);
        Assert.Equal(LastSnapshotLevel, expected.Length);

        var changed = new List<string>();
        for (int n = 1; n <= LastSnapshotLevel; n++)
        {
            string now = Describe(n);
            if (now != expected[n - 1].Trim()) changed.Add($"was {expected[n - 1].Trim()}\n  now {now}");
        }

        Assert.True(changed.Count == 0,
            $"{changed.Count} level(s) changed. First: {(changed.Count > 0 ? changed[0] : "")}");
    }

    [Fact]
    public void Level_11_is_frozen()
    {
        var expected = LevelSnapshotData.Lines.Split('\n', StringSplitOptions.RemoveEmptyEntries);
        Assert.Equal(expected[FrozenLevel - 1].Trim(), Describe(FrozenLevel));
    }

    [Fact]
    public void The_tutorial_lessons_are_frozen()
    {
        var expected = LessonSnapshotData.Lines.Split('\n', StringSplitOptions.RemoveEmptyEntries);
        Assert.Equal(StoryConfig.LessonCount, expected.Length);
        for (int n = 1; n <= StoryConfig.LessonCount; n++)
            Assert.Equal(expected[n - 1].Trim(), DescribeLesson(n));
    }

    [Fact]
    public void Building_a_level_twice_gives_the_same_level()
    {
        foreach (int n in new[] { 12, 40, 77, 126, 150, 151, 199, 200, 201, 345 })
        {
            var a = LevelCatalog.Get(n);
            Assert.Equal(Describe(n), Describe(n));
            Assert.Equal(PileHash(a), PileHash(a));
        }
    }
}
